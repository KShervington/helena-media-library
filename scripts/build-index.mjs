#!/usr/bin/env node
// Build INDEX.md from every assets/**/ASSET.md front matter, and validate the library.
//   node scripts/build-index.mjs           write INDEX.md
//   node scripts/build-index.mjs --check   exit 1 if INDEX.md is stale or an entry is invalid (for CI / pre-commit)
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { join, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const REQUIRED = ["id", "name", "description", "type", "kind", "requires", "source", "license", "origin", "used_in", "added"];
const TYPES = ["brand", "diagram", "motion", "caption", "audio", "data", "tool", "template"];
const KINDS = ["plumbing", "creative"];

function walk(dir, out = []) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (f === "ASSET.md") out.push(p);
  }
  return out;
}

function frontMatter(text, file) {
  const m = text.match(/^---\n([\s\S]*?)\n---/);
  if (!m) throw new Error(`${file}: missing front matter`);
  const o = {};
  for (const line of m[1].split("\n")) {
    const kv = line.match(/^([a-z_]+):\s*(.*)$/);
    if (!kv) continue;
    let v = kv[2].trim();
    if (v.startsWith("[") && v.endsWith("]")) v = v.slice(1, -1).split(",").map((s) => s.trim()).filter(Boolean);
    else v = v.replace(/^"(.*)"$/, "$1");
    o[kv[1]] = v;
  }
  return o;
}

const files = walk(join(ROOT, "assets"));
const assets = [];
const errors = [];
for (const f of files) {
  try {
    const a = frontMatter(readFileSync(f, "utf8"), f);
    a.path = relative(ROOT, dirname(f));
    for (const k of REQUIRED) if (a[k] === undefined) errors.push(`${a.path}: missing "${k}"`);
    if (a.type && !TYPES.includes(a.type)) errors.push(`${a.path}: type "${a.type}" not in ${TYPES.join("|")}`);
    if (a.kind && !KINDS.includes(a.kind)) errors.push(`${a.path}: kind "${a.kind}" not in ${KINDS.join("|")}`);
    if (a.preview && a.preview !== "none" && !existsSync(join(ROOT, a.path, a.preview))) errors.push(`${a.path}: preview ${a.preview} not found`);
    assets.push(a);
  } catch (e) { errors.push(e.message); }
}
const ids = new Set();
for (const a of assets) { if (ids.has(a.id)) errors.push(`duplicate id ${a.id}`); ids.add(a.id); }
for (const a of assets) for (const r of [].concat(a.requires || [])) if (!ids.has(r)) errors.push(`${a.id}: requires unknown id "${r}"`);

const byType = {};
for (const a of assets.sort((x, y) => x.id.localeCompare(y.id))) (byType[a.type] ||= []).push(a);
const lines = [
  "# Media library index",
  "",
  "<!-- Generated by scripts/build-index.mjs from each ASSET.md — do not edit by hand. -->",
  "Read this file first. Open an asset's `ASSET.md` only once you've decided to use it.",
  "`plumbing` = reuse freely · `creative` = check `used_in` and avoid repeating it in back-to-back videos.",
  "",
];
for (const t of TYPES) {
  if (!byType[t]) continue;
  lines.push(`## ${t}`, "");
  for (const a of byType[t]) {
    const req = [].concat(a.requires || []);
    const used = [].concat(a.used_in || []);
    lines.push(`- **${a.id}** · ${a.kind} · \`${a.path}/\` — ${a.description}` +
      (req.length ? ` _Requires: ${req.join(", ")}._` : "") + ` _Used in ${used.length}: last ${used[used.length - 1] || "—"}._`);
  }
  lines.push("");
}
const index = lines.join("\n");

if (errors.length) { console.error(errors.map((e) => "✗ " + e).join("\n")); process.exit(1); }
const target = join(ROOT, "INDEX.md");
if (process.argv.includes("--check")) {
  const cur = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (cur !== index) { console.error("✗ INDEX.md is out of date — run node scripts/build-index.mjs"); process.exit(1); }
  console.log(`✓ ${assets.length} assets, index current`);
} else {
  writeFileSync(target, index);
  console.log(`INDEX.md: ${assets.length} assets`);
}
